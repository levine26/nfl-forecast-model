from __future__ import annotations

"""Fail-closed HUMAN editorial publication gate (not an LLM verdict).

A candidate passing the legacy source URL/football prose validator is not
sufficient to claim actual article resolution, factual support, or launch
readiness. This gate consumes the acceptance audit regenerated by the
deterministic editorial finalizer. It never alters predictions or output.
"""

from typing import Any


class SourceAcceptanceBlocked(ValueError):
    """Full-slate HUMAN publication must be withheld pending source proof."""


def require_verified_human_sources(status: dict[str, Any], *, games_expected: int) -> None:
    if not isinstance(status, dict) or games_expected <= 0:
        raise SourceAcceptanceBlocked("invalid canonical slate or editorial audit")
    audit = status.get("editorial_acceptance")
    if not isinstance(audit, dict):
        raise SourceAcceptanceBlocked("missing deterministic editorial source-acceptance audit")
    reasons: list[str] = []
    if audit.get("article_resolution_verified") is not True:
        reasons.append("article_resolution_verified=false")
    if audit.get("claim_support_verified") is not True:
        reasons.append("claim_support_verified=false")
    if audit.get("status") != "healthy":
        reasons.append(f"acceptance_status={audit.get('status')!r}")
    if audit.get("games_expected") != games_expected:
        reasons.append(f"audit_games_expected={audit.get('games_expected')!r}, canonical={games_expected}")
    if audit.get("games_with_structurally_eligible_human_reads") != games_expected:
        reasons.append(
            "verified_human_games="
            f"{audit.get('games_with_structurally_eligible_human_reads')!r}/{games_expected}"
        )
    if audit.get("games_rejected") != 0:
        reasons.append(f"games_rejected={audit.get('games_rejected')!r}")
    if reasons:
        raise SourceAcceptanceBlocked(
            "HUMAN editorial publication refused: " + "; ".join(reasons)
            + ". URL classification and focused prose checks cannot substitute for source/claim verification."
        )
